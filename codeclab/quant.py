def scale(table, quality):
    """libjpeg と同じ品質スケーリング。quality 50 で標準テーブルそのもの。"""
    q = max(1, min(100, quality))
    factor = 5000 // q if q < 50 else 200 - q * 2
    return [[max(1, min(255, (v * factor + 50) // 100)) for v in row] for row in table]


def quantize(block, table):
    return [[round(block[y][x] / table[y][x]) for x in range(8)] for y in range(8)]


def dequantize(block, table):
    return [[block[y][x] * table[y][x] for x in range(8)] for y in range(8)]


def to_zigzag(block):
    return [block[y][x] for y, x in ZIGZAG]


def from_zigzag(seq):
    block = [[0] * 8 for _ in range(8)]
    for i, (y, x) in enumerate(ZIGZAG):
        block[y][x] = seq[i]
    return block
